import 'dart:math' as math;
import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:latlong2/latlong.dart';
import '../core/fmt.dart';
import 'db.dart';
import 'models.dart';

/// Generates clearly-labelled SYNTHETIC demo data (Product Report §5.4, §9).
/// Every record created here carries `synthetic: true` and is shown in the UI
/// with a "SYNTHETIC DEMO" badge. No official IDs, boundaries or names are used.
class DemoSeed {
  static const _names = [
    'Demo Worker A', 'Demo Worker B', 'Demo Worker C',
    'Demo Worker D', 'Demo Worker E', 'Demo Worker F',
  ];
  static const _categories = ['Overseer', 'Field Assistant', 'Work Supervisor', 'Data Entry'];

  static List<LatLng> _square(LatLng c, double halfMeters, {double rot = 0}) {
    const r = 6371000.0;
    final dLat = halfMeters / r * 180 / math.pi;
    final dLng = dLat / math.cos(c.latitude * math.pi / 180);
    final pts = <LatLng>[];
    for (int i = 0; i < 6; i++) {
      final a = rot + i * math.pi / 3;
      pts.add(LatLng(c.latitude + dLat * math.sin(a), c.longitude + dLng * math.cos(a) * 1.15));
    }
    return pts;
  }

  /// [center] is normally the admin's current GPS position so that the GIS
  /// validation can actually be demonstrated where the phone is.
  static Future<String> seed(LatLng center) async {
    final rnd = math.Random();
    final now = DateTime.now();

    // 1. Boundaries: one around the demo centre + two neighbours
    final bIds = <String>[];
    final centers = [
      center,
      LatLng(center.latitude + 0.012, center.longitude + 0.010),
      LatLng(center.latitude - 0.010, center.longitude + 0.014),
    ];
    for (int i = 0; i < centers.length; i++) {
      final ref = Db.col('boundaries').doc();
      bIds.add(ref.id);
      await ref.set({
        'name': 'Demo Zone ${String.fromCharCode(65 + i)}',
        'district': 'Chengalpattu',
        'block': 'Demo Block ${i < 2 ? 1 : 2}',
        'panchayat': 'Demo Panchayat ${i + 1}',
        'layer': 'synthetic_demo_layer',
        'attributeColumn': 'demo_id',
        'attributeValue': 'DEMO-${i + 1}',
        'source': 'Synthetic – generated by app for demonstration. NOT official GIS data.',
        'synthetic': true,
        'points': Boundary.encode(_square(centers[i], i == 0 ? 450 : 350, rot: i * 0.4)),
        'createdAt': Timestamp.now(),
      });
    }

    // 2. Workers (profile-only records, no login)
    final wIds = <String>[];
    for (int i = 0; i < _names.length; i++) {
      final ref = Db.col('users').doc();
      wIds.add(ref.id);
      await ref.set({
        'name': _names[i],
        'email': '',
        'phone': '',
        'role': Roles.worker,
        'status': i == 5 ? 'inactive' : 'active',
        'employeeId': 'DEMO-${(i + 1).toString().padLeft(3, '0')}',
        'category': _categories[i % _categories.length],
        'boundaryId': bIds[i % bIds.length],
        'hasLogin': false,
        'synthetic': true,
        'createdAt': Timestamp.now(),
      });
      // live position near their zone
      final c = centers[i % centers.length];
      final out = i == 2;
      await Db.col('locations').doc(ref.id).set({
        'uid': ref.id,
        'name': _names[i],
        'lat': c.latitude + (rnd.nextDouble() - 0.5) * (out ? 0.03 : 0.004),
        'lng': c.longitude + (rnd.nextDouble() - 0.5) * (out ? 0.03 : 0.004),
        'accuracy': 6 + rnd.nextInt(20),
        'mocked': false,
        'geoStatus': out ? 'outside' : 'inside',
        'boundaryId': bIds[i % bIds.length],
        'onDuty': i != 5,
        'synthetic': true,
        'updatedAt': Timestamp.fromDate(now.subtract(Duration(minutes: rnd.nextInt(20)))),
      });
    }

    // 3. Attendance history (7 days)
    final statuses = ['present', 'present', 'present', 'late', 'pending_verification', 'rejected'];
    for (int d = 0; d < 7; d++) {
      final day = now.subtract(Duration(days: d));
      for (int i = 0; i < 5; i++) {
        if (rnd.nextDouble() < 0.12) continue; // absent
        final st = statuses[rnd.nextInt(statuses.length)];
        final inTime = DateTime(day.year, day.month, day.day, 8, 45 + rnd.nextInt(st == 'late' ? 80 : 40));
        final faceOk = st != 'rejected';
        final c = centers[i % centers.length];
        await Db.col('attendance').doc('${wIds[i]}_${dayKey(day)}').set({
          'uid': wIds[i],
          'name': _names[i],
          'date': dayKey(day),
          'status': st,
          'synthetic': true,
          'boundaryId': bIds[i % bIds.length],
          'checkIn': {
            'time': Timestamp.fromDate(inTime),
            'lat': c.latitude,
            'lng': c.longitude,
            'accuracy': 8 + rnd.nextInt(15),
            'geoStatus': st == 'rejected' ? 'outside' : 'inside',
            'faceStatus': faceOk ? 'verified' : 'failed',
            'similarity': faceOk ? 0.70 + rnd.nextDouble() * 0.2 : 0.30 + rnd.nextDouble() * 0.2,
          },
          if (d > 0)
            'checkOut': {
              'time': Timestamp.fromDate(inTime.add(Duration(hours: 7, minutes: rnd.nextInt(90)))),
              'lat': c.latitude,
              'lng': c.longitude,
              'accuracy': 10,
              'geoStatus': 'inside',
            },
          'createdAt': Timestamp.fromDate(inTime),
        });
      }
    }

    // 4. Tasks
    const titles = [
      'Inspect village pond desilting work', 'Verify individual household latrine construction',
      'Record road repair measurement', 'Survey drinking water tank condition',
      'Upload tree plantation progress photos', 'Check solar street light installation',
      'Collect beneficiary feedback', 'Monitor check dam construction',
    ];
    const tStatus = ['assigned', 'in_progress', 'submitted', 'completed', 'completed', 'assigned', 'in_progress', 'assigned'];
    final taskIds = <String>[];
    for (int i = 0; i < titles.length; i++) {
      final ref = Db.col('tasks').doc();
      taskIds.add(ref.id);
      final w = i % 5;
      await ref.set({
        'title': titles[i],
        'description': 'Synthetic demo task for project demonstration.',
        'assignedTo': wIds[w],
        'assignedName': _names[w],
        'boundaryId': bIds[w % bIds.length],
        'priority': ['high', 'medium', 'low'][i % 3],
        'status': tStatus[i],
        'dueDate': Timestamp.fromDate(now.add(Duration(days: i - 3))),
        'createdBy': Db.uid,
        'synthetic': true,
        'createdAt': Timestamp.fromDate(now.subtract(Duration(days: 5 - (i % 5)))),
        'updatedAt': Timestamp.now(),
      });
    }

    // 5. Activities
    for (int i = 0; i < 5; i++) {
      final c = centers[i % centers.length];
      await Db.col('activities').add({
        'taskId': taskIds[i],
        'taskTitle': titles[i],
        'uid': wIds[i],
        'name': _names[i],
        'description': 'Synthetic field visit report: work observed and measurements recorded.',
        'visitType': ['Inspection', 'Survey', 'Monitoring'][i % 3],
        'lat': c.latitude,
        'lng': c.longitude,
        'accuracy': 12,
        'geoStatus': 'inside',
        'images': <String>[],
        'reviewStatus': ['pending', 'approved', 'pending', 'rejected', 'approved'][i],
        'synthetic': true,
        'createdAt': Timestamp.fromDate(now.subtract(Duration(hours: i * 7))),
      });
    }

    // 6. Alerts
    final alerts = [
      ['face_failed', 'Face verification failed for Demo Worker C at check-in.', 'high', 2],
      ['outside_boundary', 'Demo Worker C reported outside assigned boundary (620 m).', 'high', 2],
      ['late_checkin', 'Demo Worker D checked in late.', 'medium', 3],
      ['mock_location', 'Possible GPS spoofing detected on Demo Worker B\'s device.', 'critical', 1],
      ['low_accuracy', 'Low GPS accuracy (±85 m) during Demo Worker A check-in.', 'low', 0],
    ];
    for (int i = 0; i < alerts.length; i++) {
      final a = alerts[i];
      await Db.col('alerts').add({
        'type': a[0],
        'description': a[1],
        'severity': a[2],
        'uid': wIds[a[3] as int],
        'workerName': _names[a[3] as int],
        'status': i == 4 ? 'resolved' : 'open',
        'synthetic': true,
        'createdAt': Timestamp.fromDate(now.subtract(Duration(hours: i * 3))),
        'date': dayKey(now),
      });
    }
    await Db.audit('seed_demo_data', 'demo', {'workers': wIds.length, 'boundaries': bIds.length});
    return 'Created ${bIds.length} boundaries, ${wIds.length} workers, ${titles.length} tasks and 7 days of attendance (all SYNTHETIC).';
  }

  static Future<int> clear() async {
    int n = 0;
    for (final c in ['boundaries', 'users', 'attendance', 'tasks', 'activities', 'alerts', 'locations', 'verifications']) {
      final q = await Db.col(c).where('synthetic', isEqualTo: true).get();
      var batch = Db.fs.batch();
      int inBatch = 0;
      for (final d in q.docs) {
        batch.delete(d.reference);
        n++;
        if (++inBatch == 400) {
          await batch.commit();
          batch = Db.fs.batch();
          inBatch = 0;
        }
      }
      if (inBatch > 0) await batch.commit();
    }
    await Db.audit('clear_demo_data', 'demo', {'deleted': n});
    return n;
  }
}
